import { readFileSync } from 'node:fs';
import * as L from './lib.mjs';
const buf = readFileSync('assets/ai-drafts/16_bit_SNES_style_pixel_art_ga_2026-09-17T09-19-33.png');
const img = L.decodePng(buf);
console.log('decode:', img.width + 'x' + img.height, 'rgba bytes', img.rgba.length);
const keyed = L.keyOutBg(img.rgba, img.width, img.height, { mode: 'auto' });
console.log('bg detected #' + keyed.bg.map(x=>x.toString(16).padStart(2,'0')).join(''), 'keyed px', keyed.keyed, 'residualPink', keyed.residualPink);
const ds = L.blockModeDownsample(keyed.rgba, img.width, img.height, 8);
console.log('downsample:', ds.width + 'x' + ds.height, 'colors before clamp', L.countColors(ds.rgba, ds.width, ds.height));
const pal = L.buildPalette();
const cl = L.clampToPalette(ds.rgba, ds.width, ds.height, pal);
console.log('clamp: palette colors used =', cl.used.size, '/', pal.length);
const bb = L.cropBBox(cl.rgba, ds.width, ds.height);
console.log('bbox:', bb.width + 'x' + bb.height, 'at', bb.x + ',' + bb.y);
const up = L.nearestScale(bb.rgba, bb.width, bb.height, 2);
console.log('scale x2 ->', up.width + 'x' + up.height);
const o1 = L.outlineInk(up.rgba, up.width, up.height, '#2a1a12', 2);
console.log('outline done; colors final', L.countColors(o1, up.width, up.height));
const enc = L.encodePngIndexed(up.width, up.height, o1, 32);
console.log('PNG-8 bytes', enc.buf.length, 'colors', enc.colors);
